#!/usr/bin/env python3
"""Extract the drivable lower streets (tunnel/layer<0 OSM ways) into trackgen/chicago_lower_data.gd.

Source: assets/cc0-source/chicago/roadmap/downtown-roads.json (retained Overpass JSON, (c) OpenStreetMap
contributors, ODbL). Lower Randolph is mapped as "East Randolph Drive" layer -1/-2. Run from godot/.
"""
import json

NAMES = ("Lower Wacker Drive", "Lower Michigan Avenue", "East Randolph Drive")
LIMIT = 1300.0  # metres from the frame origin: the Loop + riverfront


def local(p):
    return [round((p["lon"] + 87.6244) * 82860.0, 1), round((41.8848 - p["lat"]) * 111320.0, 1)]


out = []
for e in json.load(open("assets/cc0-source/chicago/roadmap/downtown-roads.json"))["elements"]:
    t = e.get("tags", {})
    if e["type"] != "way" or not any(n in t.get("name", "") for n in NAMES):
        continue
    if t.get("tunnel") not in ("yes", "covered") or int(t.get("layer", "0")) >= 0:
        continue
    pts = [local(p) for p in e["geometry"]]
    if any(abs(x) > LIMIT or abs(z) > LIMIT for x, z in pts):
        continue
    out.append(pts)
with open("trackgen/chicago_lower_data.gd", "w") as f:
    f.write("## Generated by trackgen/data/chicago/build_lower_roads.py. Lower Wacker / Michigan / Randolph centrelines,\n")
    f.write("## local metres (x, z). Do not edit by hand.\nconst ROADS = [\n")
    for pts in out:
        f.write("\t" + json.dumps(pts).replace(" ", "") + ",\n")
    f.write("]\n")
print(len(out), "ways")
